    --header "Content-Type: application/json" \
    --header "Accept: application/json" \
    --data "{
    \"name\": \"Football Boots\",
    \"slug\": \"football-boots\",
    \"description\": \"Boots for football players.\",
    \"is_active\": true
}"
</code></pre></div>


